@app.get("/dashboard/analytics")
def dashboard_analytics():
    """
    Return aggregated analytics for the dashboard.

    Includes:
        - Risk distribution
        - Project status distribution
        - Category distribution
        - Risk-signal counts
        - Top categories by average risk
        - Overall average risk
    """

    try:
        df = load_risk_data()

    except FileNotFoundError as error:
        raise HTTPException(
            status_code=500,
            detail=str(error),
        )

    # --------------------------------------------------------
    # Risk distribution
    # --------------------------------------------------------

    risk_distribution = {
        "High": 0,
        "Medium": 0,
        "Low": 0,
    }

    if "risk_level" in df.columns:

        risk_counts = (
            df["risk_level"]
            .astype(str)
            .str.strip()
            .value_counts()
            .to_dict()
        )

        for level in risk_distribution:

            risk_distribution[level] = int(
                risk_counts.get(
                    level,
                    0,
                )
            )

    # --------------------------------------------------------
    # Status distribution
    # --------------------------------------------------------

    status_distribution = {}

    status_column = find_column(
        df,
        [
            "current_status",
            "Current_Status",
            "current status",
            "status",
            "Status",
        ],
    )

    if status_column:

        status_counts = (
            df[status_column]
            .fillna("Unknown")
            .astype(str)
            .str.strip()
            .replace("", "Unknown")
            .value_counts()
            .to_dict()
        )

        status_distribution = {
            str(key): int(value)
            for key, value
            in status_counts.items()
        }

    # --------------------------------------------------------
    # Category distribution
    # --------------------------------------------------------

    category_distribution = {}

    category_column = find_column(
        df,
        [
            "category",
            "Category",
        ],
    )

    if category_column:

        category_counts = (
            df[category_column]
            .fillna("Unknown")
            .astype(str)
            .str.strip()
            .replace("", "Unknown")
            .value_counts()
            .to_dict()
        )

        category_distribution = {
            str(key): int(value)
            for key, value
            in category_counts.items()
        }

    # --------------------------------------------------------
    # Risk signal counts
    # --------------------------------------------------------

    signal_counts = {
        "Cost Anomaly": 0,
        "Execution Delay": 0,
        "Similar / Duplicate Work": 0,
        "Unusual Spending": 0,
    }

    # Cost
    if "cost_score" in df.columns:

        numeric = pd.to_numeric(
            df["cost_score"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Cost Anomaly"] = int(
            (numeric > 0).sum()
        )

    elif "sanction_overrun_pct" in df.columns:

        numeric = pd.to_numeric(
            df["sanction_overrun_pct"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Cost Anomaly"] = int(
            (numeric > 0).sum()
        )

    # Delay
    if "delay_score" in df.columns:

        numeric = pd.to_numeric(
            df["delay_score"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Execution Delay"] = int(
            (numeric > 0).sum()
        )

    elif "delay_pct" in df.columns:

        numeric = pd.to_numeric(
            df["delay_pct"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Execution Delay"] = int(
            (numeric > 0).sum()
        )

    # Duplicate
    if "duplicate_score" in df.columns:

        numeric = pd.to_numeric(
            df["duplicate_score"],
            errors="coerce",
        ).fillna(0)

        signal_counts[
            "Similar / Duplicate Work"
        ] = int(
            (numeric > 0).sum()
        )

    elif "max_similarity_pct" in df.columns:

        numeric = pd.to_numeric(
            df["max_similarity_pct"],
            errors="coerce",
        ).fillna(0)

        signal_counts[
            "Similar / Duplicate Work"
        ] = int(
            (numeric > 0).sum()
        )

    # Spending
    if "spending_score" in df.columns:

        numeric = pd.to_numeric(
            df["spending_score"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Unusual Spending"] = int(
            (numeric > 0).sum()
        )

    elif "category_zscore" in df.columns:

        numeric = pd.to_numeric(
            df["category_zscore"],
            errors="coerce",
        ).fillna(0)

        signal_counts["Unusual Spending"] = int(
            (numeric.abs() > 0).sum()
        )

    # --------------------------------------------------------
    # Top categories by average risk
    # --------------------------------------------------------

    category_risk = []

    if (
        category_column
        and "risk_score" in df.columns
    ):

        temp = df.copy()

        temp["risk_score"] = pd.to_numeric(
            temp["risk_score"],
            errors="coerce",
        ).fillna(0)

        grouped = (
            temp
            .groupby(category_column)
            ["risk_score"]
            .agg(
                project_count="count",
                average_risk="mean",
            )
            .reset_index()
            .sort_values(
                "average_risk",
                ascending=False,
            )
        )

        for _, row in grouped.head(10).iterrows():

            category_risk.append(
                {
                    "category": str(
                        row[category_column]
                    ),

                    "project_count": int(
                        row["project_count"]
                    ),

                    "average_risk": round(
                        float(
                            row["average_risk"]
                        ),
                        2,
                    ),
                }
            )

    # --------------------------------------------------------
    # Average risk
    # --------------------------------------------------------

    average_risk = 0.0

    if "risk_score" in df.columns:

        numeric = pd.to_numeric(
            df["risk_score"],
            errors="coerce",
        ).fillna(0)

        average_risk = round(
            float(numeric.mean()),
            2,
        )

    return {
        "total_projects": int(
            len(df)
        ),

        "average_risk_score": average_risk,

        "risk_distribution":
            risk_distribution,

        "status_distribution":
            status_distribution,

        "category_distribution":
            category_distribution,

        "signal_counts":
            signal_counts,

        "top_categories_by_risk":
            category_risk,
    }


