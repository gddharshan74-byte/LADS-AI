def load_risk_data() -> pd.DataFrame:
    """
    Load project-level risk results generated by
    the PRISM AI risk engine.
    """

    if not RISK_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Risk data file not found: {RISK_DATA_PATH}"
        )

    df = pd.read_csv(RISK_DATA_PATH)

    return df


# ============================================================
# HELPER FUNCTIONS
# ============================================================

def find_column(
    df: pd.DataFrame,
    candidates: list[str],
):
    """
    Return the first matching column from candidates.
    """

    for column in candidates:
        if column in df.columns:
            return column

    return None


def normalize_text(value) -> str:
    """
    Convert a value into a clean lowercase string.
    """

    if pd.isna(value):
        return ""

    return str(value).strip().lower()


def safe_float(value, default=None):
    """
    Safely convert a value to float.
    """

    try:
        if pd.isna(value):
            return default

        return float(value)

    except (TypeError, ValueError):
        return default


def clean_number(value, decimals=2):
    """
    Safely round a number for JSON responses.
    """

    number = safe_float(value)

    if number is None:
        return None

    return round(number, decimals)


