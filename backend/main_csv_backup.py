@app.get("/projects")
def get_projects(
    risk_level: str | None = Query(
        default=None,
        description="Filter by Low, Medium, or High",
    ),
    category: str | None = Query(
        default=None,
        description="Filter by project category",
    ),
    state: str | None = Query(
        default=None,
        description="Filter by state",
    ),
    district: str | None = Query(
        default=None,
        description="Filter by district",
    ),
    status: str | None = Query(
        default=None,
        description="Filter by project status",
    ),
    limit: int = Query(
        default=100,
        ge=1,
        le=500,
    ),
):
    """
    Return project records with optional filters.
    """

    try:
        df = load_risk_data()

    except FileNotFoundError as error:
        raise HTTPException(
            status_code=500,
            detail=str(error),
        )

    # --------------------------------------------------------
    # Risk-level filter
    # --------------------------------------------------------

    if risk_level:

        valid_levels = [
            "Low",
            "Medium",
            "High",
        ]

        matched_level = next(
            (
                level
                for level in valid_levels
                if normalize_text(level)
                == normalize_text(risk_level)
            ),
            None,
        )

        if matched_level is None:
            raise HTTPException(
                status_code=400,
                detail=(
                    "risk_level must be Low, Medium, or High"
                ),
            )

        if "risk_level" not in df.columns:
            raise HTTPException(
                status_code=500,
                detail="Column 'risk_level' not found.",
            )

        df = df[
            df["risk_level"]
            .astype(str)
            .str.strip()
            == matched_level
        ]

    # --------------------------------------------------------
    # Category filter
    # --------------------------------------------------------

    if category:

        category_column = find_column(
            df,
            [
                "category",
                "Category",
            ],
        )

        if category_column:
            df = df[
                df[category_column]
                .apply(normalize_text)
                == normalize_text(category)
            ]

    # --------------------------------------------------------
    # State filter
    # --------------------------------------------------------

    if state:

        state_column = find_column(
            df,
            [
                "state",
                "State",
            ],
        )

        if state_column:
            df = df[
                df[state_column]
                .apply(normalize_text)
                == normalize_text(state)
            ]

    # --------------------------------------------------------
    # District filter
    # --------------------------------------------------------

    if district:

        district_column = find_column(
            df,
            [
                "district",
                "District",
            ],
        )

        if district_column:
            df = df[
                df[district_column]
                .apply(normalize_text)
                == normalize_text(district)
            ]

    # --------------------------------------------------------
    # Status filter
    # --------------------------------------------------------

    if status:

        status_column = find_column(
            df,
            [
                "current_status",
                "Current_Status",
                "current status",
                "status",
                "Status",
            ],
        )

        if status_column:
            df = df[
                df[status_column]
                .apply(normalize_text)
                == normalize_text(status)
            ]

    # --------------------------------------------------------
    # Sort by risk
    # --------------------------------------------------------

    if "risk_score" in df.columns:

        df["risk_score"] = pd.to_numeric(
            df["risk_score"],
            errors="coerce",
        ).fillna(0)

        df = df.sort_values(
            by="risk_score",
            ascending=False,
        )

    # --------------------------------------------------------
    # Apply limit
    # --------------------------------------------------------

    df = df.head(limit)

    # --------------------------------------------------------
    # JSON records
    # --------------------------------------------------------

    records = df.to_dict(
        orient="records"
    )

    return {
        "count": len(records),
        "projects": records,
    }


