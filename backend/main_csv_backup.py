@app.get("/projects/filter-options")
def get_filter_options():
    """
    Return unique values for dashboard filter dropdowns.
    """

    try:
        df = load_risk_data()

    except FileNotFoundError as error:
        raise HTTPException(
            status_code=500,
            detail=str(error),
        )

    def unique_values(
        candidates: list[str],
    ):

        column = find_column(
            df,
            candidates,
        )

        if not column:
            return []

        values = (
            df[column]
            .dropna()
            .astype(str)
            .str.strip()
        )

        values = [
            value
            for value in values.unique().tolist()
            if value
            and value.lower() != "nan"
            and value.lower() != "unknown"
        ]

        return sorted(values)

    return {
        "states": unique_values(
            [
                "state",
                "State",
            ]
        ),

        "districts": unique_values(
            [
                "district",
                "District",
            ]
        ),

        "categories": unique_values(
            [
                "category",
                "Category",
            ]
        ),

        "statuses": unique_values(
            [
                "current_status",
                "Current_Status",
                "current status",
                "status",
                "Status",
            ]
        ),

        "risk_levels": [
            "All",
            "High",
            "Medium",
            "Low",
        ],
    }


