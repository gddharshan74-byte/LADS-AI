@app.get("/projects/{project_id}/comparables")
def get_comparable_projects(
    project_id: str,
    limit: int = Query(
        default=5,
        ge=1,
        le=20,
    ),
):
    """
    Return projects that are most comparable to
    the selected project.

    Comparison factors:
        - Same category
        - Same district
        - Same state
        - Similar project amount
    """

    try:
        df = load_risk_data()

    except FileNotFoundError as error:
        raise HTTPException(
            status_code=500,
            detail=str(error),
        )

    if "project_id" not in df.columns:
        raise HTTPException(
            status_code=500,
            detail="Column 'project_id' not found.",
        )

    # --------------------------------------------------------
    # Find selected project
    # --------------------------------------------------------

    matches = df[
        df["project_id"]
        .astype(str)
        .str.upper()
        == project_id.upper()
    ]

    if matches.empty:
        raise HTTPException(
            status_code=404,
            detail=(
                f"Project '{project_id}' not found"
            ),
        )

    selected = matches.iloc[0]

    # --------------------------------------------------------
    # Detect useful columns
    # --------------------------------------------------------

    category_column = find_column(
        df,
        [
            "category",
            "Category",
        ],
    )

    district_column = find_column(
        df,
        [
            "district",
            "District",
        ],
    )

    state_column = find_column(
        df,
        [
            "state",
            "State",
        ],
    )

    amount_column = find_column(
        df,
        [
            "sanctioned_amount_lakh",
            "sanctioned_amount",
            "Sanctioned_Amount",
            "expenditure_lakh",
            "expenditure",
        ],
    )

    # --------------------------------------------------------
    # Candidate projects
    # --------------------------------------------------------

    candidates = df[
        df["project_id"]
        .astype(str)
        .str.upper()
        != project_id.upper()
    ].copy()

    if candidates.empty:
        return {
            "project_id": project_id,
            "count": 0,
            "comparables": [],
        }

    # --------------------------------------------------------
    # Selected attributes
    # --------------------------------------------------------

    selected_category = (
        normalize_text(
            selected[category_column]
        )
        if category_column
        else ""
    )

    selected_district = (
        normalize_text(
            selected[district_column]
        )
        if district_column
        else ""
    )

    selected_state = (
        normalize_text(
            selected[state_column]
        )
        if state_column
        else ""
    )

    # --------------------------------------------------------
    # Comparison score
    # --------------------------------------------------------

    candidates["_comparison_score"] = 0.0

    # Same category = 50 points
    if (
        category_column
        and selected_category
    ):

        candidates["_comparison_score"] += (
            candidates[category_column]
            .apply(normalize_text)
            .eq(selected_category)
            .astype(float)
            * 50
        )

    # Same district = 25 points
    if (
        district_column
        and selected_district
    ):

        candidates["_comparison_score"] += (
            candidates[district_column]
            .apply(normalize_text)
            .eq(selected_district)
            .astype(float)
            * 25
        )

    # Same state = 10 points
    if (
        state_column
        and selected_state
    ):

        candidates["_comparison_score"] += (
            candidates[state_column]
            .apply(normalize_text)
            .eq(selected_state)
            .astype(float)
            * 10
        )

    # --------------------------------------------------------
    # Amount similarity = up to 15 points
    # --------------------------------------------------------

    if amount_column:

        selected_amount = safe_float(
            selected[amount_column]
        )

        candidates["_amount_value"] = pd.to_numeric(
            candidates[amount_column],
            errors="coerce",
        )

        if selected_amount is not None:

            max_amount = max(
                abs(selected_amount),
                1,
            )

            amount_difference = (
                candidates["_amount_value"]
                .sub(selected_amount)
                .abs()
            )

            amount_similarity = (
                1
                - (
                    amount_difference
                    / max_amount
                )
            ).clip(
                lower=0,
                upper=1,
            )

            candidates["_comparison_score"] += (
                amount_similarity * 15
            )

    # --------------------------------------------------------
    # Sort
    # --------------------------------------------------------

    candidates = candidates.sort_values(
        "_comparison_score",
        ascending=False,
    )

    candidates = candidates.head(limit)

    # --------------------------------------------------------
    # Prepare response
    # --------------------------------------------------------

    output = []

    for _, row in candidates.iterrows():

        record = {
            "project_id": str(
                row.get(
                    "project_id",
                    "Unknown",
                )
            ),

            "category": (
                str(
                    row.get(
                        category_column,
                        "Unknown",
                    )
                )
                if category_column
                else "Unknown"
            ),

            "district": (
                str(
                    row.get(
                        district_column,
                        "Unknown",
                    )
                )
                if district_column
                else "Unknown"
            ),

            "state": (
                str(
                    row.get(
                        state_column,
                        "Unknown",
                    )
                )
                if state_column
                else "Unknown"
            ),

            "risk_score": clean_number(
                row.get(
                    "risk_score"
                )
            ),

            "risk_level": str(
                row.get(
                    "risk_level",
                    "Unknown",
                )
            ),

            "sanctioned_amount_lakh":
                clean_number(
                    row.get(
                        "sanctioned_amount_lakh"
                    )
                ),

            "expenditure_lakh":
                clean_number(
                    row.get(
                        "expenditure_lakh"
                    )
                ),

            "comparison_score":
                clean_number(
                    row.get(
                        "_comparison_score"
                    )
                ),
        }

        output.append(record)

    return {
        "project_id": project_id,
        "count": len(output),
        "comparables": output,
    }


