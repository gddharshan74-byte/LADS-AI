from pathlib import Path

import pandas as pd
from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware


# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).resolve().parent
RISK_DATA_PATH = BASE_DIR / "data" / "project_risk_results.csv"


# ============================================================
# FASTAPI APPLICATION
# ============================================================

app = FastAPI(
    title="LADS AI API",
    description=(
        "AI-powered risk intelligence API for MPLADS "
        "prototype project monitoring."
    ),
    version="0.1.0",
)


# ============================================================
# CORS
# ============================================================
# Allows our future React frontend to communicate with FastAPI
# while developing locally.

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Prototype only
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ============================================================
# DATA LOADING
# ============================================================

def load_risk_data() -> pd.DataFrame:
    """
    Load the project-level results generated by the LADS AI
    Risk Engine.
    """

    if not RISK_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Risk data file not found: {RISK_DATA_PATH}"
        )

    df = pd.read_csv(RISK_DATA_PATH)

    return df


